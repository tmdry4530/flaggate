# MCP tool annotations: reads are read-only; the two submit tools write only a *proposal* into the local gatekeeper
# (nothing reaches Flagsmith until a human approves), so they are non-destructive and closed-world. Clients such as
# Codex use these hints to decide which calls need their own approval.
_PROPOSE = {"plan_from_prompt", "submit_plan"}
for _t in TOOL_SPECS:
    _t["annotations"] = ({"readOnlyHint": False, "destructiveHint": False, "idempotentHint": False,
                          "openWorldHint": False} if _t["name"] in _PROPOSE else
                         {"readOnlyHint": True, "openWorldHint": False})
TOOL_NAMES = [t["name"] for t in TOOL_SPECS]


# ----------------------------------------------------------------------------- JSON-RPC / MCP plumbing
class MCPServer:
    def __init__(self, tools: Tools):
        self.tools = tools

    def handle(self, msg: dict[str, Any]) -> dict[str, Any] | None:
        mid, method, params = msg.get("id"), msg.get("method"), msg.get("params") or {}
        if mid is None:  # notification (e.g. notifications/initialized)
            return None
        try:
            if method == "initialize":
                want = params.get("protocolVersion")
                return self._ok(mid, {"protocolVersion": want if want in PROTOCOLS else PROTOCOLS[0],
                                      "capabilities": {"tools": {"listChanged": False}},
                                      "serverInfo": {"name": SERVER_NAME, "version": SERVER_VERSION},
                                      "instructions": INSTRUCTIONS})
            if method == "ping":
                return self._ok(mid, {})
            if method == "tools/list":
                return self._ok(mid, {"tools": TOOL_SPECS})
            if method == "tools/call":
                return self._ok(mid, self.call(params.get("name"), params.get("arguments") or {}))
            if method in ("resources/list", "prompts/list"):
                return self._ok(mid, {method.split("/")[0]: []})
            return {"jsonrpc": "2.0", "id": mid, "error": {"code": -32601, "message": f"method not found: {method}"}}
        except Exception as e:  # noqa: BLE001
            return {"jsonrpc": "2.0", "id": mid, "error": {"code": -32603, "message": str(e)}}

    def call(self, name: str | None, args: dict[str, Any]) -> dict[str, Any]:
        if name not in TOOL_NAMES:
            return self._tool_result({"error": f"unknown tool {name!r}. This server cannot apply, approve or roll back; "
                                      "a human runs `fg approve <plan_id>`."}, error=True)
        try:
            out = getattr(self.tools, name)(**args)
        except GatekeeperError as e:
            return self._tool_result({"status": e.status, **e.body}, error=True)
        except (TypeError, ValueError) as e:
            return self._tool_result({"error": str(e)}, error=True)
        return self._tool_result(out)

    @staticmethod
    def _tool_result(obj: Any, error: bool = False) -> dict[str, Any]:
        text = json.dumps(obj, ensure_ascii=False, indent=1, default=str)
        return {"content": [{"type": "text", "text": text}], "isError": error}

    @staticmethod
    def _ok(mid: Any, result: Any) -> dict[str, Any]:
        return {"jsonrpc": "2.0", "id": mid, "result": result}

    def serve(self, stdin=None, stdout=None) -> None:
        stdin, stdout = stdin or sys.stdin, stdout or sys.stdout
        for line in stdin:
            line = line.strip()
            if not line:
                continue
            try:
                msg = json.loads(line)
            except json.JSONDecodeError:
                resp: dict[str, Any] | None = {"jsonrpc": "2.0", "id": None,
                                               "error": {"code": -32700, "message": "parse error"}}
            else:
                resp = self.handle(msg)
            if resp is not None:
                stdout.write(json.dumps(resp, ensure_ascii=False) + "\n")
                stdout.flush()


def main() -> None:
    scrub_environment()
    MCPServer(Tools(GatekeeperClient(agent_socket()))).serve()


if __name__ == "__main__":
    main()
