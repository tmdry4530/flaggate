class Tools:
    def __init__(self, gk: GatekeeperClient, clock: Callable[[], float] = time.monotonic,
                 sleep: Callable[[float], None] = time.sleep):
        self.gk, self.clock, self.sleep = gk, clock, sleep

    def snapshot(self) -> dict[str, Any]:
        r = self.gk.snapshot()
        return _summary(r["snapshot"], r["state_hash"])

    def read_features(self) -> dict[str, Any]:
        s = self.snapshot()
        return {"base_state_hash": s["base_state_hash"], "features": s["features"]}

    def read_feature(self, name: str) -> dict[str, Any]:
        s = self.snapshot()
        if name not in s["features"]:
            raise ValueError(f"unknown feature {name!r}; known: {', '.join(s['features'])}")
        return {"base_state_hash": s["base_state_hash"], "feature": name, **s["features"][name]}

    def read_segments(self) -> dict[str, Any]:
        s = self.snapshot()
        return {"base_state_hash": s["base_state_hash"], "segments": s["segments"]}

    def plan_schema(self) -> dict[str, Any]:
        s = self.snapshot()
        return {**PLAN_HELP, "template": {
            "schema": "flaggate.plan/v1", "plan_id": "pl_YYYYMMDD_xxxx", "created_at": "<now, ISO-8601 with tz>",
            "author": "agent:<name>", "prompt": "<the user's request>", "target": s["target"],
            "base_state_hash": s["base_state_hash"], "ops": [], "guardrails": {"max_exposure_pct": 20},
            "expires_at": "<created_at + 1h>"}}

    def plan_from_prompt(self, prompt: str) -> dict[str, Any]:
        return _bundle_view(self.gk.plan_from_prompt(prompt, actor="agent:mcp"))

    def submit_plan(self, plan: dict[str, Any] | str) -> dict[str, Any]:
        if isinstance(plan, str):
            plan = json.loads(plan)
        return _bundle_view(self.gk.submit(plan, actor="agent:mcp"))

    def plan_status(self, plan_id: str) -> dict[str, Any]:
        return self.gk.status(plan_id)

    def wait_for_result(self, plan_id: str, timeout_s: float = 45) -> dict[str, Any]:
        timeout_s = max(0.0, min(float(timeout_s), MAX_WAIT_S))
        end = self.clock() + timeout_s
        while True:
            st = self.gk.status(plan_id)
            if st.get("status") in TERMINAL:
                return {**st, "done": True}
            if self.clock() >= end:
                return {**st, "done": False,
                        "hint": "still waiting for the human approval; call wait_for_result again"}
            self.sleep(1.0)


